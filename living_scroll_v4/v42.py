#!/usr/bin/env python3
"""V4.2 Art/Morphing Pass: V4.1 geometry + procedural shan-shui + flying ink.
All transformations are generated by Blender keyframes; no generative video API.
"""
from pathlib import Path
import argparse
import math
import random
import sys
import bpy

HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE))
import scene as v4

OUT=HERE/"renders_v42"
OUT.mkdir(parents=True,exist_ok=True)
SEED=424242
R=random.Random(SEED)
FPS=24
END=288

def diamond_mesh():
    mesh=bpy.data.meshes.new("MORPH_SHARED_BROKEN_INK_DAB")
    mesh.from_pydata([(-1.0,0,0),(0,-.015,.36),(1.0,0,.18),(.20,.008,-.34)],
                     [],[(0,1,3),(1,2,3)])
    mesh.update()
    return mesh

def scatter_to_birds():
    collection=v4.coll("V42_09_INK_MORPH")
    carbon=v4.em("MORPH_Carbon_Stipples",(.023,.031,.028))
    mid=v4.em("MORPH_Dry_Brush",(.13,.16,.14))
    cinnabar=v4.em("MORPH_Cinnabar_Dust",(.64,.16,.10))
    mesh=diamond_mesh()
    N=172
    for i in range(N):
        a=(2*math.pi*i/N)+R.uniform(-.11,.11)
        radial=R.uniform(.22,1.60)*(.76+.24*math.cos(i*.18))
        origin=(math.cos(a)*radial,-3.02+R.uniform(-.06,.06),
                .16+math.sin(a)*radial*.92)
        bird=i%7
        line=i//7
        dx=.45*(bird%4)
        dz=.38*(bird//4)
        x=-1.5+dx+R.uniform(-.19,.19)
        z=.37+dz+R.uniform(-.08,.13)
        target=(x,-3.2,z)
        target2=(x+R.uniform(.26,.84),-3.08,z+R.uniform(.25,.69))
        ob=bpy.data.objects.new("MORPH_PIGMENT_%03d"%i,mesh)
        collection.objects.link(ob)
        ob.data.materials.clear() if i==0 else None
        ob.location=origin
        # shared mesh/material means predictable style and low memory overhead
        ob.scale=(.001,)*3
        jitter=R.uniform(.0,.35)
        ob.rotation_euler[1]=R.uniform(-.8,.8)
        mat=carbon if i%11 else cinnabar if i%22==0 else mid
        # Mesh is shared; material randomization by object impossible without material indices.
        # Use a consistent carbon material for all dabs.
        if i==0: mesh.materials.append(carbon)
        x0,y0,z0=origin
        # Temporal distribution intentionally overlaps lotus collapse (frames 139-175).
        times=[
          (115,(x0,y0,z0),.001),
          (128+(i%8),(x0,y0,z0),.029+R.random()*.055),
          (150+(i%9),(x0*.85,y0-.03,z0+.13),.045+R.random()*.065),
          (176+(i%12),target,.055+R.random()*.07),
          (209,target2,.022+R.random()*.03),
          (236,target2,.001)
        ]
        for frame,pos,scale in times:
            ob.location=pos
            ob.scale=(scale*R.uniform(.68,1.5),scale*.6,scale*R.uniform(.9,1.8))
            ob.keyframe_insert("location",frame=frame)
            ob.keyframe_insert("scale",frame=frame)
        for f,az in [(125,0),(168,R.uniform(-2.7,2.7)),(218,R.uniform(-1.0,1.0))]:
            ob.rotation_euler[1]=az;ob.keyframe_insert("rotation_euler",frame=f)
    # Additional separated broad ink brush arcs—curves remain in 3D.
    for i in range(15):
        ang=2*math.pi*(i+.25)/15
        a=math.cos(ang);b=math.sin(ang)
        pts=[]
        for k in range(11):
            t=k/10
            x=a*(.25+1.48*t)+.10*math.sin(t*7+i)
            z=b*(.25+1.48*t)*.85+.1
            y=-3.10-.07*math.sin(2*t*math.pi)
            pts.append((x,y,z))
        cu=bpy.data.curves.new("MORPH_Stroke_%02d"%i,"CURVE")
        cu.dimensions="3D"
        cu.bevel_depth=.012
        cu.bevel_resolution=1
        cu.bevel_factor_start=0.0
        cu.bevel_factor_end=0.0
        sp=cu.splines.new("POLY")
        sp.points.add(10)
        for p,coords in zip(sp.points,pts):
            p.co=(*coords,1)
        ob=bpy.data.objects.new("MORPH_BRUSH_STROKE_%02d"%i,cu)
        collection.objects.link(ob)
        cu.materials.append(carbon)
        for f,v in [(1,0.0),(120,0.0),(147,1.0),(172,1.0),(202,0.0)]:
            cu.bevel_factor_end=v;cu.keyframe_insert("bevel_factor_end",frame=f)
        for f,v in [(1,0.0),(162,0.0),(198,1.0)]:
            cu.bevel_factor_start=v;cu.keyframe_insert("bevel_factor_start",frame=f)
    return N

def add_sky_ink_particles():
    group=v4.coll("V42_10_PAPER_SPARKS")
    carbon=v4.em("V42_Ink_Fibers",(.16,.18,.17))
    mesh=bpy.data.meshes.new("V42_FIBER_MESH")
    mesh.from_pydata([(-.032,0,-.008),(.032,0,0),(.007,0,.21)],
                    [],[(0,1,2)])
    mesh.update()
    mesh.materials.append(carbon)
    for i in range(35):
        ob=bpy.data.objects.new("FIBER_%03d"%i,mesh)
        group.objects.link(ob)
        x=R.uniform(-2.4,2.4);z=R.uniform(-3.7,3.8)
        y=-2.86
        v=R.uniform(.16,.52)
        for frame,pos,s in [(1,(x,y,z),.001),(140,(x,y,z),.001),
                            (177,(x,y,z),v),(248,(x+.15,y,z+R.uniform(-.2,.2)),v*.6),
                            (285,(x+.23,y,z+.33),.001)]:
            ob.location=pos;ob.scale=(s,s,s)
            ob.keyframe_insert("location",frame=frame)
            ob.keyframe_insert("scale",frame=frame)

def validate(count):
    s=bpy.context.scene
    if count<160:raise RuntimeError("Missing ink morph agents")
    if not bpy.data.objects.get("MORPH_PIGMENT_000"):raise RuntimeError("Ink particle control missing")
    for n in ("LOTUS_HERO_CTRL","PAVILION_FOREGROUND_CTRL","BIRD_00_RIG","SCROLL_REVEAL_CTRL"):
        if not bpy.data.objects.get(n):raise RuntimeError("Regressed V4 object: "+n)
    if s.frame_end!=288 or s.render.fps!=24:raise RuntimeError("Timeline changed")
    print("V42_QA_PASS: models, ink redistribution, frames", count)

def main(smoke=False,full=False):
    if not (HERE.parent/"living_scroll_v3"/"assets"/"far_mountains.png").exists():
        raise SystemExit("Run V3 generate_assets.py then v42_art.py before Blender.")
    v4.build(False,False)
    n=scatter_to_birds()
    add_sky_ink_particles()
    validate(n)
    scene=bpy.context.scene
    scene.frame_set(1)
    scene.render.resolution_x=360 if smoke else 720
    scene.render.resolution_y=640 if smoke else 1280
    bpy.ops.file.pack_all()
    path=HERE/"living_scroll_v42.blend"
    bpy.ops.wm.save_as_mainfile(filepath=str(path))
    sample=[1,48,88,115,139,155,175,216,275] if smoke else range(1,END+1)
    if smoke or full:
        for f in sample:
            scene.frame_set(f)
            scene.render.filepath=str(OUT/(("smoke_%03d"%f) if smoke else ("frame_%04d"%f)))
            bpy.ops.render.render(write_still=True)
    print("V42_RENDER_COMPLETE",path)

if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--smoke",action="store_true")
    p.add_argument("--full",action="store_true")
    a=sys.argv[sys.argv.index("--")+1:] if "--" in sys.argv else []
    opt=p.parse_args(a)
    if opt.smoke and opt.full:p.error("Only one render mode")
    main(opt.smoke,opt.full)
