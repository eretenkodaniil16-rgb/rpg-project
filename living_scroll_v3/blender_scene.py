#!/usr/bin/env python3
"""The Living Scroll V3, Blender 5.2 headless render.
All assets may be generated by generate_assets.py; authored PNGs are optional.
Usage: blender -b --python-exit-code 1 --python living_scroll_v3/blender_scene.py -- --smoke
       blender -b --python-exit-code 1 --python living_scroll_v3/blender_scene.py -- --render
"""
from pathlib import Path
import argparse
import math
import random
import sys

import bpy

ROOT=Path(__file__).resolve().parent
ASSETS=ROOT/"assets"
OUTPUT=ROOT/"renders"
FPS=24
FRAME_END=288
R=random.Random(31030)

def create_ink_material(name,rgba,metallic=0.0):
    m=bpy.data.materials.new(name)
    m.use_nodes=True
    principled=m.node_tree.nodes.get("Principled BSDF")
    principled.inputs["Base Color"].default_value=rgba
    principled.inputs["Metallic"].default_value=metallic
    principled.inputs["Roughness"].default_value=.77 if not metallic else .35
    m.diffuse_color=rgba
    return m

def paint_material(name,path):
    if not path.exists():
        raise FileNotFoundError(str(path))
    m=bpy.data.materials.new(name)
    m.use_nodes=True
    nt=m.node_tree
    nt.nodes.clear()
    tex=nt.nodes.new("ShaderNodeTexImage")
    tex.image=bpy.data.images.load(str(path),check_existing=True)
    tex.interpolation="Linear"
    emissive=nt.nodes.new("ShaderNodeEmission")
    transparent=nt.nodes.new("ShaderNodeBsdfTransparent")
    mix=nt.nodes.new("ShaderNodeMixShader")
    alpha=nt.nodes.new("ShaderNodeMath")
    alpha.operation="MULTIPLY"
    alpha.inputs[1].default_value=1.0
    out=nt.nodes.new("ShaderNodeOutputMaterial")
    nt.links.new(tex.outputs["Color"],emissive.inputs["Color"])
    nt.links.new(tex.outputs["Alpha"],alpha.inputs[0])
    nt.links.new(alpha.outputs[0],mix.inputs[0])
    nt.links.new(transparent.outputs[0],mix.inputs[1])
    nt.links.new(emissive.outputs[0],mix.inputs[2])
    nt.links.new(mix.outputs[0],out.inputs["Surface"])
    if hasattr(m,"surface_render_method"):
        try: m.surface_render_method="DITHERED"
        except (ValueError,TypeError): pass
    return m,alpha

def plane(name,y,material):
    bpy.ops.mesh.primitive_plane_add(size=2,location=(0,y,0))
    obj=bpy.context.object
    obj.name=name
    obj.rotation_euler[0]=math.pi/2
    obj.scale=(5.625/2,10.0/2,1.0)
    obj.data.materials.append(material)
    return obj

def loc_keys(obj,keys):
    for frame,xyz in keys:
        obj.location=xyz
        obj.keyframe_insert("location",frame=frame)

def scale_keys(obj,keys):
    for frame,v in keys:
        obj.scale=(v,v,v)
        obj.keyframe_insert("scale",frame=frame)

def opacity_keys(node,keys):
    for frame,opacity in keys:
        node.inputs[1].default_value=opacity
        node.inputs[1].keyframe_insert(data_path="default_value",frame=frame)

def create_swallow(i,ink):
    root=bpy.data.objects.new("Swallow_%02d"%i,None)
    bpy.context.collection.objects.link(root)
    bpy.ops.mesh.primitive_uv_sphere_add(segments=12,ring_count=8)
    body=bpy.context.object
    body.name="Swallow_%02d_Body"%i
    body.parent=root
    body.location=(0,0,0)
    body.scale=(.21,.06,.09)
    body.data.materials.append(ink)
    for side in (-1,1):
        mesh=bpy.data.meshes.new("Feather_Mesh")
        mesh.from_pydata([(0,0,0),(.38*side,.01,.13),(.9*side,.04,.28),(.56*side,.01,-.06)],
                         [],[(0,1,3),(1,2,3)])
        mesh.update()
        wing=bpy.data.objects.new("Swallow_%02d_Wing_%s"%(i,"L" if side<0 else "R"),mesh)
        bpy.context.collection.objects.link(wing)
        wing.parent=root
        wing.data.materials.append(ink)
        for frame in range(1,FRAME_END+1,8):
            t=frame/FPS
            wing.rotation_euler[1]=side*(.35+.6*math.sin(t*9+i*.7))
            wing.keyframe_insert("rotation_euler",frame=frame)
    x=-1.9+(i%4)*.48
    z=.45+(i//4)*.37
    delay=i*4
    loc_keys(root,[(90+delay,(x-.8,-1.2,z-.6)),
                   (143+delay,(x,-1.45,z)),
                   (190+delay,(x+.7,-1.8,z+.85)),
                   (270,(x+3.2,-2.1,z+2.5))])
    scale_keys(root,[(1,.001),(95+delay,.001),
                    (125+delay,.35),(155+delay,.48),(288,.63)])

def build(smoke=False,render=False):
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    s=bpy.context.scene
    # Prefer EEVEE, but use enum introspection rather than assume old API spellings.
    engines=[e.identifier for e in bpy.types.RenderSettings.bl_rna.properties["engine"].enum_items]
    selected=next((e for e in ("BLENDER_EEVEE_NEXT","BLENDER_EEVEE") if e in engines),None)
    if selected is None:
        selected="BLENDER_WORKBENCH" if "BLENDER_WORKBENCH" in engines else s.render.engine
    s.render.engine=selected
    # Workbench does not display the material node alpha shader; treat that as unsupported.
    if selected=="BLENDER_WORKBENCH":
        raise RuntimeError("The Blender build lacks EEVEE; cannot render transparent ink layers")
    s.render.resolution_x=360 if smoke else 720
    s.render.resolution_y=640 if smoke else 1280
    s.render.resolution_percentage=100
    s.render.image_settings.file_format="PNG"
    s.render.image_settings.color_mode="RGBA"
    s.render.film_transparent=False
    s.frame_start=1
    s.frame_end=FRAME_END
    s.render.fps=FPS
    s.view_settings.view_transform="Standard"
    OUTPUT.mkdir(parents=True,exist_ok=True)

    bpy.ops.object.camera_add(location=(0,-13,0))
    cam=bpy.context.object
    cam.name="Living_Scroll_Camera"
    cam.rotation_euler=(math.pi/2,0,0)
    cam.data.type="ORTHO"
    cam.data.ortho_scale=10.3
    s.camera=cam
    loc_keys(cam,[(1,(-.11,-13,0)),(70,(.12,-13,0)),
                  (160,(-.20,-12.7,.16)),(230,(.18,-13,0)),
                  (288,(0,-13,0))])
    for f,v in [(1,10.3),(190,9.5),(239,10.5),(288,12.5)]:
        cam.data.ortho_scale=v
        cam.data.keyframe_insert("ortho_scale",frame=f)

    layers=[
      ("Papyrus", "paper.png",2.3,[(1,1),(288,1)],0),
      ("World_Backdrop","landscape_master.png",1.65,[(1,0),(95,0),(145,.50),(181,1),(288,1)],0),
      ("Far_Mountains","far_mountains.png",.75,[(1,0),(136,0),(161,.62),(190,1),(288,1)],.05),
      ("Middle_Mountains","mid_mountains.png",-.25,[(1,0),(149,0),(173,.70),(203,1),(288,1)],.12),
      ("Near_Mountains","near_mountains.png",-.81,[(1,0),(159,0),(184,.76),(207,1),(288,1)],.19),
      ("Lotus_Bloom","lotus_focus.png",-1.03,[(1,0),(15,.05),(38,.95),(106,1),(147,.6),(175,0),(288,0)],-.07)
    ]
    for name,filename,depth,keys,shift in layers:
        material,alpha=paint_material(name+"_Ink",ASSETS/filename)
        obj=plane(name,depth,material)
        opacity_keys(alpha,keys)
        loc_keys(obj,[(1,(0,depth,0)),(168,(shift,depth,0)),
                      (245,(-shift/2,depth,0)),(288,(0,depth,0))])

    ink=create_ink_material("Carbon_Black_Ink",(.018,.022,.021,1))
    bronze=create_ink_material("Burnished_Bronze",(.36,.20,.09,1),metallic=.75)
    # The first painted droplet is modelled rather than baked into an image.
    bpy.ops.mesh.primitive_uv_sphere_add(segments=36,ring_count=20,location=(0,-1.2,3.6))
    drop=bpy.context.object
    drop.name="Ink_Droplet"
    drop.data.materials.append(ink)
    loc_keys(drop,[(1,(0,-1.2,3.6)),(26,(0,-1.2,.48)),(38,(0,-1.2,.12)),(65,(0,-1.2,.12))])
    for frame,xyz in [(1,(.12,.055,.18)),(27,(.12,.055,.18)),(39,(.42,.04,.03)),(58,(.001,.001,.001))]:
        drop.scale=xyz;drop.keyframe_insert("scale",frame=frame)

    for i in range(7):create_swallow(i,ink)

    for sign in (-1,1):
        bpy.ops.mesh.primitive_cylinder_add(vertices=40,radius=.13,depth=10.6,
                                             location=(sign*2.92,-1.2,0))
        roller=bpy.context.object
        roller.name=("Left" if sign<0 else "Right")+"_Scroll_Roller"
        roller.data.materials.append(bronze)
        scale_keys(roller,[(1,.001),(224,.001),(253,1),(288,1)])

    s.frame_set(1)
    path=ROOT/"living_scroll_v3.blend"
    bpy.ops.file.pack_all()
    bpy.ops.wm.save_as_mainfile(filepath=str(path))
    frames=(1,48,105,158,220,275) if smoke else range(1,FRAME_END+1)
    if smoke or render:
        for frame in frames:
            s.frame_set(frame)
            s.render.filepath=str(OUTPUT/(("smoke_%03d"%frame) if smoke else ("frame_%04d"%frame)))
            bpy.ops.render.render(write_still=True)
    print("LIVING_SCROLL_RENDER_OK",path,"mode=","smoke" if smoke else "full" if render else "scene-only")

if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--smoke",action="store_true")
    p.add_argument("--render",action="store_true")
    argv=sys.argv[sys.argv.index("--")+1:] if "--" in sys.argv else []
    args=p.parse_args(argv)
    if args.smoke and args.render:
        p.error("Choose smoke or render")
    build(smoke=args.smoke,render=args.render)
